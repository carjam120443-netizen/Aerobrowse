    companion object {
        fun fromId(id: String?): AeroThemePreset =
            entries.firstOrNull { it.id == id } ?: SKY_AERO
    }
}

data class AeroPalette(
    val preset: AeroThemePreset,
    val colorScheme: ColorScheme,
    val backdropGradient: List<Color>,
    val backdropTint: Color,
    val glassSurface: Color,
    val glassSurfaceElevated: Color,
    val glassBorderHighlight: Color,
    val glassBorderShadow: Color,
    val glassSheenTop: Color,
    val glassSheenBottom: Color,
    val accentGlow: Color,
    val shieldActive: Color,
    val burnAccent: Color,
    val onBackdrop: Color,
)

